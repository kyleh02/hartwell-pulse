export function EmojiPicker({ onPick }: { onPick: (emoji: string) => void }) {
  const [query, setQuery] = useState("");
  const inputRef = useRef<HTMLInputElement>(null);

  // Autofocus for keyboard users on desktop only. On touch screens focusing
  // would throw the on-screen keyboard over the picker.
  useEffect(() => {
    if (window.matchMedia("(pointer: fine)").matches) {
      inputRef.current?.focus();
    }
  }, []);

  const q = query.trim().toLowerCase();
  const tokens = q.split(/\s+/).filter(Boolean);
  const matches =
    tokens.length > 0
      ? CATEGORIES.flatMap((c) => c.items).filter((it) =>
          tokens.every((t) => it.n.includes(t)),
        )
      : null;

  return (
    <div>
      <div className="flex items-center gap-2 border-b border-pulse-border px-3 py-2">
        <Search size={13} className="shrink-0 text-pulse-text-mute" />
        <input
          ref={inputRef}
          value={query}
          onChange={(e) => setQuery(e.target.value)}
          placeholder="Search emojis…"
          className="min-w-0 flex-1 bg-transparent text-sm text-pulse-text placeholder:text-pulse-text-mute focus:outline-none"
        />
      </div>
      <div className="max-h-[min(18rem,45vh)] overflow-y-auto p-2">
        {matches ? (
          matches.length === 0 ? (
            <p className="px-1 py-3 text-center text-xs text-pulse-text-mute">
              No emojis match &ldquo;{query.trim()}&rdquo;
            </p>
          ) : (
            <div className="grid grid-cols-8 gap-0.5">
              {matches.map((it) => (
                <button
                  key={it.e}
                  type="button"
                  onClick={() => onPick(it.e)}
                  title={it.n}
                  className="rounded p-1 text-lg leading-none hover:bg-pulse-surface-2"
                >
                  {it.e}
                </button>
              ))}
            </div>
          )
        ) : (
          CATEGORIES.map((c) => (
            <div key={c.label}>
              <p className="mono-label px-1 pb-1 pt-2 first:pt-0">{c.label}</p>
              <div className="grid grid-cols-8 gap-0.5">
                {c.items.map((it) => (
                  <button
                    key={it.e}
                    type="button"
                    onClick={() => onPick(it.e)}
                    title={it.n}
                    className="rounded p-1 text-lg leading-none hover:bg-pulse-surface-2"
                  >
                    {it.e}
                  </button>
                ))}
              </div>
            </div>
          ))
        )}
      </div>
    </div>
  );
}
